package simh

import (
	"fmt"
	"strings"

	"pdp11emu/server/internal/api"
)

// The generated part of run.ini is defined here, next to the code that
// interprets the simulator's reaction to it (internal/systems writes it).

// RunHeader returns the generated header of run.ini (DESIGN §6): CPU,
// memory, speed, console, panel export. Its length depends on the speed.
func RunHeader(memory string, speed api.Speed, consolePort int, shmPath string) []string {
	h := []string{"; generated by pdp11d - do not edit", "set cpu 11/70", "set cpu " + memory}
	h = append(h, SpeedCommands(speed)...)
	return append(h,
		fmt.Sprintf("set console -u telnet=127.0.0.1:%d;notelnet", consolePort),
		"set console telnet=buffered=65536",
		"set tto 7b",
		"attach panel "+shmPath,
	)
}

// SpeedCommands are the SCP commands that select a speed (DESIGN §9):
// fast idles in WAIT, authentic is throttled to about 1 MIPS. This is the
// single definition (run.ini header, SetSpeed, the boot matrix follows it).
//
// Fast uses plain "set cpu idle": SimH pre-calibrates at start-up and sets
// the idle stability wait to 0, while "idle=2" raises it back to 2 s; the
// first 2 s of a boot then spin through WAIT unthrottled, which inflates
// the calibrated instructions per tick about 4x and costs host CPU for the
// rest of the run.
func SpeedCommands(s api.Speed) []string {
	if s == api.SpeedAuthentic {
		return []string{"set throttle 1M"}
	}
	return []string{"set nothrottle", "set cpu idle"}
}

// TerminalsAttach is the run.ini line, appended after boot.ini, that puts
// a system's terminal lines on the PDP11_TTY_TELNET listener ("-m": modem
// control, DZ only).
func TerminalsAttach(device string, modem bool, listen string) string {
	if modem && device == "dz" {
		return "attach -u -m " + device + " " + listen
	}
	return "attach -u " + device + " " + listen
}

// CheckPath rejects file names SimH cannot take as a command argument.
func CheckPath(p string) error {
	if p == "" || strings.ContainsAny(p, " \t\r\n\"';") {
		return fmt.Errorf("path %q: SimH cannot use paths containing blanks, quotes or ';'", p)
	}
	return nil
}
