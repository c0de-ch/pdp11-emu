def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def disk_image() -> bytes:
    """8 blocks: data, zeros, data, zeros x4, a short tail."""
    b = bm.BLOCK
    return (b"A" * b) + bytes(b) + (b"B" * 100 + bytes(b - 100)) + bytes(4 * b) + b"tail"


